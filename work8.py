# Variables are names used to store a value. 
# You can create a variable by giving it a name and assiting a value to it.

# Data types tell Python what kind of value something is.
# Examples :

# 1. STRING (str)
# A string is text written inside quotation marks.
# name = "Victor"
# 2. INTEGER (int)
# An integer is a whole number without a decimal point.
# age = 25
# 3. FLOAT (float)
# A float is a number that has a decimal point.
# price = 2500.50
# 4. BOOLEAN (bool)
# Boolean has only two values: True or False.
# is_available = True
# 5. LIST (list)
# A list stores multiple values in one variable.
# Lists are written using square brackets [].
# products = ["rice", "beans", "bread", "milk"]
# 6. DICTIONARY (dict)
# A dictionary stores data using KEY and VALUE pairs.
# Dictionaries are written using curly brackets {}.
# student = {
#     "name": "Victor",
#     "age": 25,
#     "course": "Software Engineering"
# }
# 7. TUPLE (tuple)
# A tuple is similar to a list, but its values cannot be changed.
# Tuples are written using parentheses ().
# colors = ("red", "blue", "green")

# Operators are symbols used to perform operations on values.
# Examples :
# 1. ARITHMETIC OPERATORS
# Used for mathematical calculations.
# a = 10
# b = 3

# print(a + b)   # Addition
# print(a - b)   # Subtraction
# print(a * b)   # Multiplication
# print(a / b)   # Division
# print(a // b)  # Floor division
# print(a % b)   # Modulus (remainder)
# print(a ** b)  # Exponent
# 2. COMPARISON OPERATORS
# Used to compare two values.
# They return True or False.
# x = 10
# y = 5

# print(x == y)   # Equal to
# print(x != y)   # Not equal to
# print(x > y)    # Greater than
# print(x < y)    # Less than
# print(x >= y)   # Greater than or equal to
# print(x <= y)   # Less than or equal to
# 3. ASSIGNMENT OPERATORS
# Used to assign or update values.
# number = 10

# number += 5     # Same as number = number + 5
# print(number)

# number -= 2     # Same as number = number - 2
# print(number)

# number *= 2     # Same as number = number * 2
# print(number)

# number /= 2     # Same as number = number / 2
# print(number)
# 4. LOGICAL OPERATORS
# Used to combine conditions.
# age = 25

# print(age > 18 and age < 30)  # Both conditions must be True
# print(age > 30 or age == 25)  # At least one condition must be True
# print(not age == 25)          # Reverses True to False
